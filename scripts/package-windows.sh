#!/usr/bin/env bash
# Package the staged Windows build: scripts/package-windows.sh [version]
#
# Input:  build/windows/rPlayHub/  (scripts/build-windows.sh makes it)
# Output: build/windows/rPlayHub-<version>-setup-x64.exe   per-user NSIS installer
#         build/windows/rPlayHub-<version>-windows-x64.zip portable: unzip anywhere, run rplay-gui.exe
#
# Run inside MSYS2 UCRT64 (needs makensis: mingw-w64-ucrt-x86_64-nsis). The version defaults to
# RPLAYHUB_VERSION in client-c/Makefile, which is also what the Linux .deb carries.
#
# Optional Authenticode signing. Set RPLAYHUB_SIGN_CMD to a command line that signs ONE file,
# given as its final argument (a Windows path); it is run on every .exe and .dll in the staged
# folder before they are zipped or packed, on the uninstaller as NSIS generates it, and on the
# finished installer. Example with signtool and Azure Trusted Signing:
#
#   export RPLAYHUB_SIGN_CMD='"/c/Program Files (x86)/Windows Kits/10/bin/10.0.26100.0/x64/signtool.exe" sign
#       /v /fd SHA256 /tr http://timestamp.acs.microsoft.com /td SHA256
#       /dlib C:\\path\\Azure.CodeSigning.Dlib.dll /dmdf C:\\path\\metadata.json'
#
# Without it nothing is signed, and Windows SmartScreen warns on first run ("Windows protected
# your PC" -> More info -> Run anyway).
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
die() { echo "package-windows: error: $*" >&2; exit 1; }

[ "${MSYSTEM:-}" = UCRT64 ] || die "run inside MSYS2 UCRT64 (see scripts/build-windows.sh)"
version="${1:-$(sed -n 's/^RPLAYHUB_VERSION := \([0-9.]*\).*/\1/p' client-c/Makefile)}"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "version must be x.y.z, got '$version'"
out="$root/build/windows"
stage="$out/rPlayHub"
[ -f "$stage/rplay-gui.exe" ] && [ -f "$stage/cdhost.exe" ] || die "$stage is not staged -- run scripts/build-windows.sh first"
command -v makensis >/dev/null || die "makensis missing (pacman -S mingw-w64-ucrt-x86_64-nsis)"

installer="$out/rPlayHub-$version-setup-x64.exe"
zipfile="$out/rPlayHub-$version-windows-x64.zip"
rm -f "$installer" "$zipfile"

sign() {   # sign <file>
    local w; w="$(cygpath -w "$1")"
    echo "  signing $(basename "$1")"
    eval "$RPLAYHUB_SIGN_CMD \"\$w\"" || die "signing $1 failed"
}
if [ -n "${RPLAYHUB_SIGN_CMD:-}" ]; then
    export RPLAYHUB_SIGN_CMD     # the uninstaller is signed from a child process, below
    echo "package-windows: signing the staged executables and DLLs"
    for f in "$stage"/*.exe "$stage"/*.dll; do sign "$f"; done
else
    echo "package-windows: RPLAYHUB_SIGN_CMD not set -- building UNSIGNED (SmartScreen will warn)"
fi

# The uninstaller deletes exactly what was staged, so it cannot take anything else with it.
uninst_list="$out/uninstall-files.nsh"
{
    echo "; generated by scripts/package-windows.sh -- the files installed from $stage"
    ( cd "$stage" && find . -type f | sed 's|^\./||' | sort ) | while read -r f; do
        printf 'Delete "$INSTDIR\\%s"\n' "${f//\//\\}"
    done
    ( cd "$stage" && find . -mindepth 1 -type d | sed 's|^\./||' | sort -r ) | while read -r d; do
        printf 'RMDir "$INSTDIR\\%s"\n' "${d//\//\\}"
    done
} > "$uninst_list"

nsis_args=(-V2
    "-DVERSION=$version"
    "-DSTAGE=$(cygpath -w "$stage")"
    "-DOUTFILE=$(cygpath -w "$installer")"
    "-DUNINST_LIST=$(cygpath -w "$uninst_list")")
if [ -n "${RPLAYHUB_SIGN_CMD:-}" ]; then
    # makensis runs !uninstfinalize through cmd.exe, so hand it a .cmd that re-enters bash and
    # runs the same RPLAYHUB_SIGN_CMD (inherited through the environment) on the uninstaller.
    signer="$out/sign-file.cmd"
    printf '@"%s" -lc %s sign "%%~1"\r\n' "$(cygpath -w /usr/bin/bash.exe)" \
        "'eval \"\$RPLAYHUB_SIGN_CMD \\\"\$1\\\"\"'" > "$signer"
    nsis_args+=("-DUNINST_SIGN=\"$(cygpath -w "$signer")\" \"%1\"")
    # makensis runs it via %COMSPEC%, which an MSYS2 login shell may not have -- and then it
    # crashes ("basic_string: construction from null") instead of reporting it.
    export COMSPEC="${COMSPEC:-${SYSTEMROOT:-C:\\Windows}\\System32\\cmd.exe}"
fi
echo "package-windows: building the installer"
# MSYS2_ARG_CONV_EXCL: these are already Windows paths; keep MSYS from rewriting -D values.
MSYS2_ARG_CONV_EXCL='*' makensis "${nsis_args[@]}" "$(cygpath -w packaging/windows/rplayhub.nsi)"
[ -f "$installer" ] || die "makensis produced no installer"
[ -n "${RPLAYHUB_SIGN_CMD:-}" ] && sign "$installer"

echo "package-windows: building the portable zip"
if command -v zip >/dev/null; then
    ( cd "$out" && zip -qr9 "$(basename "$zipfile")" rPlayHub )
else
    ( cd "$out" && python3 -m zipfile -c "$(basename "$zipfile")" rPlayHub )
fi
[ -f "$zipfile" ] || die "zip not produced"

echo
for f in "$installer" "$zipfile"; do
    printf 'package-windows: %s  (%s KB, sha256 %s)\n' "${f#$root/}" "$(( $(stat -c %s "$f") / 1024 ))" \
        "$(sha256sum "$f" | cut -c1-16)..."
done
